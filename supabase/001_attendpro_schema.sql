-- Review + optional correction in one Postgres transaction.
CREATE OR REPLACE FUNCTION public.attendpro_resolve_discrepancy(
  p_employee_id bigint,p_work_date date,p_issue text,p_resolution text,
  p_note text,p_actor uuid,p_after jsonb DEFAULT NULL
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE v_result jsonb := '{}'::jsonb;
BEGIN
  IF NOT EXISTS(SELECT 1 FROM public.attendpro_app_users WHERE auth_id=p_actor AND active=true
     AND role IN ('supervisor','super_admin')) THEN
    RAISE EXCEPTION 'Not authorized to resolve discrepancies';
  END IF;
  IF p_resolution NOT IN ('reviewed','present','on_leave') THEN
    RAISE EXCEPTION 'Invalid discrepancy resolution';
  END IF;
  IF p_resolution IN ('present','on_leave') AND length(trim(coalesce(p_note,'')))<3 THEN
    RAISE EXCEPTION 'Provide a reason for attendance correction';
  END IF;
  IF p_resolution IN ('present','on_leave') THEN
    v_result:=public.attendpro_save_correction(p_employee_id,p_work_date,p_after,p_actor,
      'discrepancy_'||p_resolution,p_note,NULL);
  END IF;
  INSERT INTO public.attendpro_discrepancy_reviews(employee_id,work_date,issue_type,resolution,
      note,reviewed_by)
  VALUES(p_employee_id,p_work_date,p_issue,p_resolution,coalesce(p_note,''),p_actor)
  ON CONFLICT(employee_id,work_date,issue_type) DO UPDATE SET
      resolution=excluded.resolution,note=excluded.note,reviewed_by=excluded.reviewed_by,
      reviewed_at=now();
  RETURN jsonb_build_object('success',true,'correction',v_result);
END $$;
REVOKE ALL ON FUNCTION public.attendpro_resolve_discrepancy(bigint,date,text,text,text,uuid,jsonb) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.attendpro_resolve_discrepancy(bigint,date,text,text,text,uuid,jsonb) TO service_role;

-- Cloud-generated employee IDs prevent collisions between different application hosts.
CREATE OR REPLACE FUNCTION public.attendpro_create_employee(
  p_actor uuid, p_device_user_id text,p_badge_number text,p_name text,
  p_department text,p_designation text,p_shift text
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE v_id bigint; v_record jsonb;
BEGIN
 IF NOT EXISTS(SELECT 1 FROM public.attendpro_app_users WHERE auth_id=p_actor AND active=true AND role='super_admin')
 THEN RAISE EXCEPTION 'Only Super Admin can create employees'; END IF;
 IF length(trim(coalesce(p_name,'')))<2 THEN RAISE EXCEPTION 'Employee name required'; END IF;
 PERFORM pg_advisory_xact_lock(981234,1123);
 IF p_badge_number IS NOT NULL AND trim(p_badge_number)<>'' AND EXISTS(
    SELECT 1 FROM public.attendpro_employees WHERE badge_number=p_badge_number)
 THEN RAISE EXCEPTION 'Badge number is already assigned'; END IF;
 SELECT coalesce(max(id),0)+1 INTO v_id FROM public.attendpro_employees;
 INSERT INTO public.attendpro_employees(id,device_user_id,badge_number,name,department,designation,shift)
 VALUES(v_id,p_device_user_id,nullif(p_badge_number,''),p_name,p_department,p_designation,p_shift);
 SELECT to_jsonb(e) INTO v_record FROM public.attendpro_employees e WHERE e.id=v_id;
 RETURN v_record;
END $$;
REVOKE ALL ON FUNCTION public.attendpro_create_employee(uuid,text,text,text,text,text,text) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.attendpro_create_employee(uuid,text,text,text,text,text,text) TO service_role;

