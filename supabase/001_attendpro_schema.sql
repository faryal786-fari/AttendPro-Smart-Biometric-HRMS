-- AttendPro schema. Run once in Supabase SQL Editor before enabling cloud mode.
-- Source database att2000.mdb is NEVER modified by this migration.
-- This project intentionally exposes NO direct table access from the browser:
-- signed-in users use Supabase Auth; FastAPI enforces roles and uses a server-only secret key.
CREATE TABLE IF NOT EXISTS public.attendpro_app_users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  auth_id uuid NOT NULL UNIQUE REFERENCES auth.users(id) ON DELETE CASCADE,
  email text NOT NULL UNIQUE,
  display_name text NOT NULL,
  role text NOT NULL CHECK (role IN ('view_only','supervisor','super_admin')),
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.attendpro_employees (
  id bigint PRIMARY KEY,
  device_user_id text NOT NULL UNIQUE,
  source_userid text,
  badge_number text,
  name text NOT NULL,
  department text NOT NULL DEFAULT 'Unassigned',
  designation text NOT NULL DEFAULT 'Staff',
  shift text NOT NULL DEFAULT 'General',
  phone text DEFAULT '', email text DEFAULT '',
  biometric_enrollment text NOT NULL DEFAULT 'unknown' CHECK(biometric_enrollment IN ('unknown','configured','not_configured')),
  active boolean NOT NULL DEFAULT true,
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.attendpro_source_daily (
  employee_id bigint NOT NULL REFERENCES public.attendpro_employees(id),
  work_date date NOT NULL,
  status text NOT NULL,
  clock_in text,clock_out text,
  late_minutes int, early_minutes int, work_minutes int,
  shift text,source text NOT NULL DEFAULT 'mdb',raw_absent text,
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY(employee_id,work_date)
);
CREATE INDEX IF NOT EXISTS idx_attendpro_source_date ON public.attendpro_source_daily(work_date DESC);
-- Each imported event remains immutable. An UPDATE is never part of the normal ingest path.
CREATE TABLE IF NOT EXISTS public.attendpro_raw_punches (
  event_key text PRIMARY KEY,
  employee_id bigint REFERENCES public.attendpro_employees(id),
  device_user_id text NOT NULL,
  happened_at timestamp without time zone NOT NULL,
  kind text NOT NULL,
  source text NOT NULL,
  raw_status text,
  imported_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_attendpro_punch_employee ON public.attendpro_raw_punches(employee_id,happened_at DESC);
-- Effective attendance = source daily + latest, explicitly approved correction.
-- Never UPDATE the source to apply manual edits.
CREATE TABLE IF NOT EXISTS public.attendpro_corrections (
  employee_id bigint NOT NULL REFERENCES public.attendpro_employees(id),
  work_date date NOT NULL,
  after_json jsonb NOT NULL,
  version int NOT NULL DEFAULT 1,
  updated_by uuid NOT NULL REFERENCES auth.users(id),
  action text NOT NULL,
  reason text NOT NULL,
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY(employee_id,work_date)
);
CREATE TABLE IF NOT EXISTS public.attendpro_correction_audit (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  employee_id bigint NOT NULL,
  work_date date NOT NULL,
  before_json jsonb,
  after_json jsonb NOT NULL,
  version int NOT NULL,
  updated_by uuid NOT NULL REFERENCES auth.users(id),
  action text NOT NULL,
  reason text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_attendpro_audit_employee_date ON public.attendpro_correction_audit(employee_id,work_date,created_at DESC);
CREATE TABLE IF NOT EXISTS public.attendpro_discrepancy_reviews (
  employee_id bigint NOT NULL REFERENCES public.attendpro_employees(id),
  work_date date NOT NULL,
  issue_type text NOT NULL,
  resolution text NOT NULL,
  note text NOT NULL DEFAULT '',
  reviewed_by uuid NOT NULL REFERENCES auth.users(id),
  reviewed_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY(employee_id,work_date,issue_type)
);
CREATE TABLE IF NOT EXISTS public.attendpro_devices (
  id bigint PRIMARY KEY,
  name text NOT NULL,
  model text NOT NULL,
  serial_number text,
  -- MDB is a path on your own trusted server, NOT a cloud-accessible file.
  auto_sync boolean NOT NULL DEFAULT false,
  sync_interval int NOT NULL DEFAULT 90,
  status text NOT NULL DEFAULT 'not_configured',
  last_sync text
);

-- All cloud tables remain backend-only; role permissions are enforced by FastAPI.
-- RLS is defense-in-depth, even if someone obtains the publishable key.
DO $$ DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY[
    'attendpro_app_users','attendpro_employees','attendpro_source_daily',
    'attendpro_raw_punches','attendpro_corrections','attendpro_correction_audit',
    'attendpro_discrepancy_reviews','attendpro_devices'] LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY',t);
    EXECUTE format('REVOKE ALL ON TABLE public.%I FROM anon,authenticated',t);
  END LOOP;
END $$;
-- No anon/authenticated SELECT/INSERT/UPDATE/DELETE policies are created intentionally.

CREATE OR REPLACE FUNCTION public.attendpro_save_correction(
  p_employee_id bigint, p_work_date date, p_after jsonb,
  p_actor uuid, p_action text, p_reason text,
  p_expected_version int DEFAULT NULL
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = public,pg_temp AS $$
DECLARE v_previous jsonb; v_version int; v_result jsonb;
BEGIN
  IF NOT EXISTS(SELECT 1 FROM public.attendpro_app_users
       WHERE auth_id=p_actor AND active=true AND role IN ('supervisor','super_admin')) THEN
    RAISE EXCEPTION 'Actor is not authorized to edit attendance';
  END IF;
  IF NOT EXISTS(SELECT 1 FROM public.attendpro_employees WHERE id=p_employee_id) THEN
    RAISE EXCEPTION 'Employee not found';
  END IF;
  IF p_after IS NULL OR jsonb_typeof(p_after) <> 'object' THEN
    RAISE EXCEPTION 'Invalid correction payload';
  END IF;
  IF length(trim(coalesce(p_reason,''))) < 3 THEN
    RAISE EXCEPTION 'Correction reason must contain at least 3 characters';
  END IF;
  -- Serialize edits for the same employee and day, including first-ever edits.
  PERFORM pg_advisory_xact_lock(hashtext('attendpro:correction:'||p_employee_id::text), (p_work_date - date '2000-01-01')::integer);
  SELECT after_json, version INTO v_previous,v_version
      FROM public.attendpro_corrections WHERE employee_id=p_employee_id AND work_date=p_work_date FOR UPDATE;
  IF p_expected_version IS NOT NULL AND coalesce(v_version,0)<>p_expected_version THEN
    RAISE EXCEPTION 'The attendance changed. Refresh before saving';
  END IF;
  IF v_previous IS NULL THEN
    SELECT jsonb_build_object('status',status,'clock_in',clock_in,'clock_out',clock_out,
        'late_minutes',late_minutes,'early_minutes',early_minutes,
        'work_minutes',work_minutes,'shift',shift)
      INTO v_previous FROM public.attendpro_source_daily
      WHERE employee_id=p_employee_id AND work_date=p_work_date;
  END IF;
  v_version := coalesce(v_version,0)+1;
  INSERT INTO public.attendpro_corrections(employee_id,work_date,after_json,version,updated_by,action,reason)
    VALUES(p_employee_id,p_work_date,p_after,v_version,p_actor,p_action,p_reason)
  ON CONFLICT(employee_id,work_date) DO UPDATE SET
    after_json=excluded.after_json,version=excluded.version,updated_by=excluded.updated_by,
    action=excluded.action,reason=excluded.reason,updated_at=now();
  INSERT INTO public.attendpro_correction_audit(employee_id,work_date,before_json,after_json,
      version,updated_by,action,reason)
    VALUES(p_employee_id,p_work_date,v_previous,p_after,v_version,p_actor,p_action,p_reason);
  RETURN jsonb_build_object('employee_id',p_employee_id,'work_date',p_work_date,
    'version',v_version,'after_json',p_after);
END;
$$;
REVOKE ALL ON FUNCTION public.attendpro_save_correction(bigint,date,jsonb,uuid,text,text,int) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.attendpro_save_correction(bigint,date,jsonb,uuid,text,text,int) TO service_role;
