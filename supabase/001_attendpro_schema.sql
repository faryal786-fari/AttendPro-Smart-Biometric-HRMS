CREATE OR REPLACE FUNCTION public.attendpro_set_biometric_status(
 p_actor uuid,p_employee_id bigint,p_status text,p_note text DEFAULT ''
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE v_previous text;
BEGIN
 IF NOT EXISTS(SELECT 1 FROM public.attendpro_app_users WHERE auth_id=p_actor AND active=true
       AND role IN ('supervisor','super_admin')) THEN RAISE EXCEPTION 'Not authorized';END IF;
 IF p_status NOT IN ('unknown','configured','not_configured') THEN RAISE EXCEPTION 'Invalid enrollment status';END IF;
 SELECT biometric_enrollment INTO v_previous FROM public.attendpro_employees WHERE id=p_employee_id FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'Employee not found';END IF;
 UPDATE public.attendpro_employees SET biometric_enrollment=p_status,updated_at=now() WHERE id=p_employee_id;
 INSERT INTO public.attendpro_biometric_audit(employee_id,prior_status,new_status,changed_by,note)
 VALUES(p_employee_id,v_previous,p_status,p_actor,coalesce(p_note,''));
 RETURN jsonb_build_object('prior_status',v_previous,'new_status',p_status);
END $$;
REVOKE ALL ON FUNCTION public.attendpro_set_biometric_status(uuid,bigint,text,text) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.attendpro_set_biometric_status(uuid,bigint,text,text) TO service_role;


-- Defense in depth: source punch events and correction audit cannot be edited or
-- deleted through ordinary SQL updates (except by explicitly dropping this trigger).
CREATE OR REPLACE FUNCTION public.attendpro_reject_evidence_mutation()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'Biometric evidence and audit rows are immutable';END $$;
DROP TRIGGER IF EXISTS attendpro_protect_raw_punches ON public.attendpro_raw_punches;
CREATE TRIGGER attendpro_protect_raw_punches BEFORE UPDATE OR DELETE
 ON public.attendpro_raw_punches FOR EACH ROW EXECUTE FUNCTION public.attendpro_reject_evidence_mutation();
DROP TRIGGER IF EXISTS attendpro_protect_audit ON public.attendpro_correction_audit;
CREATE TRIGGER attendpro_protect_audit BEFORE UPDATE OR DELETE
 ON public.attendpro_correction_audit FOR EACH ROW EXECUTE FUNCTION public.attendpro_reject_evidence_mutation();
