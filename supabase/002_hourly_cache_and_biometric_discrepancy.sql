-- Human edits always take ownership of the latest correction, even if the
-- previous version was generated by the scheduler.
CREATE OR REPLACE FUNCTION public.attendpro_save_correction(
  p_employee_id bigint, p_work_date date, p_after jsonb,
  p_actor uuid, p_action text, p_reason text,
  p_expected_version int DEFAULT NULL
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = public,pg_temp AS $$
DECLARE v_previous jsonb; v_version int;
BEGIN
  IF NOT EXISTS(SELECT 1 FROM public.attendpro_app_users
       WHERE auth_id=p_actor AND active=true AND role IN ('supervisor','super_admin')) THEN
    RAISE EXCEPTION 'Actor is not authorized to edit attendance';
  END IF;
  IF NOT EXISTS(SELECT 1 FROM public.attendpro_employees WHERE id=p_employee_id) THEN
    RAISE EXCEPTION 'Employee not found';
  END IF;
  IF p_after IS NULL OR jsonb_typeof(p_after) <> 'object' THEN
    RAISE EXCEPTION 'Invalid correction payload';
  END IF;
  IF length(trim(coalesce(p_reason,''))) < 3 THEN
    RAISE EXCEPTION 'Correction reason must contain at least 3 characters';
  END IF;
  PERFORM pg_advisory_xact_lock(hashtext('attendpro:correction:'||p_employee_id::text), (p_work_date - date '2000-01-01')::integer);
  SELECT after_json, version INTO v_previous,v_version
      FROM public.attendpro_corrections WHERE employee_id=p_employee_id AND work_date=p_work_date FOR UPDATE;
  IF p_expected_version IS NOT NULL AND coalesce(v_version,0)<>p_expected_version THEN
    RAISE EXCEPTION 'The attendance changed. Refresh before saving';
  END IF;
  IF v_previous IS NULL THEN
    SELECT jsonb_build_object('status',status,'clock_in',clock_in,'clock_out',clock_out,
        'late_minutes',late_minutes,'early_minutes',early_minutes,
        'work_minutes',work_minutes,'shift',shift)
      INTO v_previous FROM public.attendpro_source_daily
      WHERE employee_id=p_employee_id AND work_date=p_work_date;
  END IF;
  v_version := coalesce(v_version,0)+1;
  INSERT INTO public.attendpro_corrections(employee_id,work_date,after_json,version,updated_by,action,reason,actor_type,actor_label)
    VALUES(p_employee_id,p_work_date,p_after,v_version,p_actor,p_action,p_reason,'user','Authenticated user')
  ON CONFLICT(employee_id,work_date) DO UPDATE SET
    after_json=excluded.after_json,version=excluded.version,updated_by=excluded.updated_by,
    action=excluded.action,reason=excluded.reason,updated_at=now(),
    actor_type='user',actor_label='Authenticated user';
  INSERT INTO public.attendpro_correction_audit(employee_id,work_date,before_json,after_json,
      version,updated_by,action,reason,actor_type,actor_label)
    VALUES(p_employee_id,p_work_date,v_previous,p_after,v_version,p_actor,p_action,p_reason,'user','Authenticated user');
  RETURN jsonb_build_object('employee_id',p_employee_id,'work_date',p_work_date,
    'version',v_version,'after_json',p_after);
END;
$$;
REVOKE ALL ON FUNCTION public.attendpro_save_correction(bigint,date,jsonb,uuid,text,text,int) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.attendpro_save_correction(bigint,date,jsonb,uuid,text,text,int) TO service_role;

-- Update the existing review RPC so human reviews are clearly labelled as user actions.
CREATE OR REPLACE FUNCTION public.attendpro_resolve_discrepancy(
  p_employee_id bigint,p_work_date date,p_issue text,p_resolution text,
  p_note text,p_actor uuid,p_after jsonb DEFAULT NULL
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE v_result jsonb := '{}'::jsonb;
BEGIN
  IF NOT EXISTS(SELECT 1 FROM public.attendpro_app_users WHERE auth_id=p_actor AND active=true
     AND role IN ('supervisor','super_admin')) THEN
    RAISE EXCEPTION 'Not authorized to resolve discrepancies';
  END IF;
  IF p_resolution NOT IN ('reviewed','present','on_leave') THEN
    RAISE EXCEPTION 'Invalid discrepancy resolution';
  END IF;
  IF p_resolution IN ('present','on_leave') AND length(trim(coalesce(p_note,'')))<3 THEN
    RAISE EXCEPTION 'Provide a reason for attendance correction';
  END IF;
  IF p_resolution IN ('present','on_leave') THEN
    v_result:=public.attendpro_save_correction(p_employee_id,p_work_date,p_after,p_actor,
      'discrepancy_'||p_resolution,p_note,NULL);
  END IF;
  INSERT INTO public.attendpro_discrepancy_reviews(employee_id,work_date,issue_type,resolution,
      note,reviewed_by,actor_type,actor_label)
  VALUES(p_employee_id,p_work_date,p_issue,p_resolution,coalesce(p_note,''),p_actor,'user','Authenticated user')
  ON CONFLICT(employee_id,work_date,issue_type) DO UPDATE SET
      resolution=excluded.resolution,note=excluded.note,reviewed_by=excluded.reviewed_by,
      reviewed_at=now(),actor_type='user',actor_label='Authenticated user';
  RETURN jsonb_build_object('success',true,'correction',v_result);
END $$;
REVOKE ALL ON FUNCTION public.attendpro_resolve_discrepancy(bigint,date,text,text,text,uuid,jsonb) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.attendpro_resolve_discrepancy(bigint,date,text,text,text,uuid,jsonb) TO service_role;

-- Automatic rule:
-- Only an employee explicitly marked biometric_enrollment='not_configured',
-- with an original MDB check-in and no existing correction, is automatically
-- marked On Leave in the effective Supabase correction layer.
-- Unknown enrollment is NOT treated as unconfigured. Existing human corrections
-- are never overwritten. The raw source_daily and raw_punches remain unchanged.
CREATE OR REPLACE FUNCTION public.attendpro_apply_biometric_exception(
  p_employee_id bigint,p_work_date date,p_note text
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE
  v_enrollment text;
  v_source public.attendpro_source_daily%ROWTYPE;
  v_actor uuid;
  v_after jsonb;
  v_before jsonb;
  v_version int;
BEGIN
  PERFORM pg_advisory_xact_lock(hashtext('attendpro:correction:'||p_employee_id::text),
                                (p_work_date - date '2000-01-01')::integer);
  SELECT biometric_enrollment INTO v_enrollment
    FROM public.attendpro_employees WHERE id=p_employee_id FOR UPDATE;
  IF NOT FOUND OR v_enrollment <> 'not_configured' THEN
    RETURN jsonb_build_object('applied',false,'reason','Biometric enrollment is not explicitly Not Configured');
  END IF;

  SELECT * INTO v_source FROM public.attendpro_source_daily
    WHERE employee_id=p_employee_id AND work_date=p_work_date;
  IF NOT FOUND OR v_source.clock_in IS NULL THEN
    RETURN jsonb_build_object('applied',false,'reason','No source check-in exists');
  END IF;
  IF NOT EXISTS(SELECT 1 FROM public.attendpro_raw_punches
       WHERE employee_id=p_employee_id AND happened_at::date=p_work_date) THEN
    RETURN jsonb_build_object('applied',false,'reason','No original biometric punch exists');
  END IF;
  IF EXISTS(SELECT 1 FROM public.attendpro_corrections
       WHERE employee_id=p_employee_id AND work_date=p_work_date) THEN
    RETURN jsonb_build_object('applied',false,'reason','An existing correction was preserved');
  END IF;

  SELECT auth_id INTO v_actor FROM public.attendpro_app_users
    WHERE active=true AND role='super_admin' ORDER BY created_at LIMIT 1;
  IF v_actor IS NULL THEN
    RAISE EXCEPTION 'An active Super Admin is required as the system audit owner';
  END IF;

  v_before:=jsonb_build_object('status',v_source.status,'clock_in',v_source.clock_in,
    'clock_out',v_source.clock_out,'late_minutes',v_source.late_minutes,
    'early_minutes',v_source.early_minutes,'work_minutes',v_source.work_minutes,'shift',v_source.shift);
  v_after:=jsonb_build_object('status','on_leave','clock_in',v_source.clock_in,
    'clock_out',v_source.clock_out,'late_minutes',v_source.late_minutes,
    'early_minutes',v_source.early_minutes,'work_minutes',v_source.work_minutes,'shift',v_source.shift);
  v_version:=1;

  INSERT INTO public.attendpro_corrections(employee_id,work_date,after_json,version,updated_by,action,reason,actor_type,actor_label)
    VALUES(p_employee_id,p_work_date,v_after,v_version,v_actor,'auto_biometric_not_configured',
      coalesce(nullif(trim(p_note),''),'Automatic biometric enrollment exception'),'system','AttendPro Scheduler');
  INSERT INTO public.attendpro_correction_audit(employee_id,work_date,before_json,after_json,
      version,updated_by,action,reason,actor_type,actor_label)
    VALUES(p_employee_id,p_work_date,v_before,v_after,v_version,v_actor,
      'auto_biometric_not_configured',coalesce(nullif(trim(p_note),''),'Automatic biometric enrollment exception'),
      'system','AttendPro Scheduler');

  INSERT INTO public.attendpro_discrepancy_reviews(employee_id,work_date,issue_type,resolution,note,reviewed_by,actor_type,actor_label)
    VALUES(p_employee_id,p_work_date,'biometric_not_configured','on_leave',coalesce(p_note,''),v_actor,'system','AttendPro Scheduler')
    ON CONFLICT(employee_id,work_date,issue_type) DO UPDATE SET resolution='on_leave',note=excluded.note,
      reviewed_by=excluded.reviewed_by,reviewed_at=now(),actor_type='system',actor_label='AttendPro Scheduler';
  INSERT INTO public.attendpro_discrepancy_reviews(employee_id,work_date,issue_type,resolution,note,reviewed_by,actor_type,actor_label)
    VALUES(p_employee_id,p_work_date,'leave_with_punch','on_leave',coalesce(p_note,''),v_actor,'system','AttendPro Scheduler')
    ON CONFLICT(employee_id,work_date,issue_type) DO UPDATE SET resolution='on_leave',note=excluded.note,
      reviewed_by=excluded.reviewed_by,reviewed_at=now(),actor_type='system',actor_label='AttendPro Scheduler';

  RETURN jsonb_build_object('applied',true,'version',v_version,'after_json',v_after,
    'actor_type','system','actor_label','AttendPro Scheduler','original_source_changed',false);
END;
$$;
REVOKE ALL ON FUNCTION public.attendpro_apply_biometric_exception(bigint,date,text) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.attendpro_apply_biometric_exception(bigint,date,text) TO service_role;

