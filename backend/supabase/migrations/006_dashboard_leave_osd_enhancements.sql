-- AttendPro dashboard, OSD Permanent and leave/holiday announcements.
-- Additive migration only: existing attendance and raw biometric records are preserved.

ALTER TABLE public.pts_osd_records
  ADD COLUMN IF NOT EXISTS osd_type text NOT NULL DEFAULT 'temporary';

DO $$ BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname='pts_osd_records_osd_type_check'
      AND conrelid='public.pts_osd_records'::regclass
  ) THEN
    ALTER TABLE public.pts_osd_records
      ADD CONSTRAINT pts_osd_records_osd_type_check
      CHECK (osd_type IN ('temporary','permanent'));
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS ix_pts_osd_type_dates
  ON public.pts_osd_records(person_type,osd_type,status,start_at,end_at);

CREATE TABLE IF NOT EXISTS public.pts_leave_announcements (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL,
  message text NOT NULL DEFAULT '',
  start_date date NOT NULL,
  end_date date NOT NULL,
  audience text NOT NULL DEFAULT 'all'
    CHECK (audience IN ('all','staff','trainee')),
  active boolean NOT NULL DEFAULT true,
  created_by text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (end_date >= start_date)
);
CREATE INDEX IF NOT EXISTS ix_pts_leave_announcements_dates
  ON public.pts_leave_announcements(active,start_date,end_date);

CREATE TABLE IF NOT EXISTS public.pts_holidays (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL,
  holiday_date date NOT NULL,
  category text NOT NULL DEFAULT 'Institutional',
  description text NOT NULL DEFAULT '',
  created_by text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_pts_holidays_date
  ON public.pts_holidays(holiday_date);

-- These records are accessed only by the FastAPI server using service_role.
DO $$ DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['pts_leave_announcements','pts_holidays'] LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY',t);
    EXECUTE format('REVOKE ALL ON TABLE public.%I FROM PUBLIC, anon, authenticated',t);
    EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.%I TO service_role',t);
  END LOOP;
END $$;

GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO service_role;
