-- PTC Lahore / Manawan training management foundation.
-- Apply after migrations 001-004 in the PTC Lahore Supabase project.
-- Do NOT apply this migration to another academy's database.

CREATE TABLE IF NOT EXISTS public.pts_trainees (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_no text NOT NULL,
  name text NOT NULL,
  father_name text NOT NULL DEFAULT '',
  course_name text NOT NULL DEFAULT '',
  platoon text NOT NULL DEFAULT '',
  course_start_date date,
  course_end_date date,
  status text NOT NULL DEFAULT 'active'
    CHECK (status IN ('active','repatriated','completed')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_pts_trainees_course
  ON public.pts_trainees(employee_no,course_name,platoon,course_start_date,course_end_date,status);

CREATE TABLE IF NOT EXISTS public.pts_trainee_attendance (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  trainee_id bigint NOT NULL REFERENCES public.pts_trainees(id) ON DELETE CASCADE,
  attendance_date date NOT NULL,
  shift text NOT NULL DEFAULT 'Morning' CHECK (shift IN ('Morning','Evening')),
  status text NOT NULL CHECK (status IN ('present','absent','late','early_arrival','leave','osd','medical_rest','long_weekend')),
  check_in text,
  check_out text,
  course_name text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(trainee_id,attendance_date,shift)
);
CREATE INDEX IF NOT EXISTS ix_pts_trainee_attendance_date
  ON public.pts_trainee_attendance(attendance_date,shift,status);

CREATE TABLE IF NOT EXISTS public.pts_leave_records (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  person_type text NOT NULL CHECK(person_type IN ('trainee','staff')),
  person_id text NOT NULL,
  person_name text NOT NULL,
  course_name text NOT NULL DEFAULT '',
  platoon text NOT NULL DEFAULT '',
  staff_category text NOT NULL DEFAULT '',
  staff_branch text NOT NULL DEFAULT '',
  leave_type text NOT NULL,
  start_at timestamptz NOT NULL,
  end_at timestamptz NOT NULL,
  reason text NOT NULL,
  reference_no text NOT NULL DEFAULT '',
  remarks text NOT NULL DEFAULT '',
  status text NOT NULL DEFAULT 'pending'
    CHECK(status IN ('pending','approved','rejected','cancelled','exempt')),
  created_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK(end_at >= start_at)
);
CREATE INDEX IF NOT EXISTS ix_pts_leave_dates
  ON public.pts_leave_records(person_type,status,start_at,end_at);

CREATE TABLE IF NOT EXISTS public.pts_osd_records (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  person_type text NOT NULL CHECK(person_type IN ('trainee','staff')),
  person_id text NOT NULL,
  person_name text NOT NULL,
  course_name text NOT NULL DEFAULT '',
  platoon text NOT NULL DEFAULT '',
  staff_category text NOT NULL DEFAULT '',
  staff_branch text NOT NULL DEFAULT '',
  start_at timestamptz NOT NULL,
  end_at timestamptz NOT NULL,
  reason text NOT NULL,
  duty_place text NOT NULL DEFAULT '',
  reference_no text NOT NULL DEFAULT '',
  remarks text NOT NULL DEFAULT '',
  status text NOT NULL DEFAULT 'pending'
    CHECK(status IN ('pending','approved','rejected','cancelled','exempt')),
  created_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK(end_at >= start_at)
);
CREATE INDEX IF NOT EXISTS ix_pts_osd_dates
  ON public.pts_osd_records(person_type,status,start_at,end_at);

CREATE TABLE IF NOT EXISTS public.pts_duty_rest_records (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  person_type text NOT NULL DEFAULT 'staff' CHECK(person_type='staff'),
  person_id text NOT NULL,
  person_name text NOT NULL,
  staff_category text NOT NULL DEFAULT '',
  staff_branch text NOT NULL DEFAULT '',
  start_at timestamptz NOT NULL,
  end_at timestamptz NOT NULL,
  reason text NOT NULL DEFAULT 'Duty Rest',
  reference_no text NOT NULL DEFAULT '',
  remarks text NOT NULL DEFAULT '',
  status text NOT NULL DEFAULT 'approved'
    CHECK(status IN ('pending','approved','rejected','cancelled','exempt')),
  created_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK(end_at >= start_at)
);
CREATE INDEX IF NOT EXISTS ix_pts_duty_rest_dates
  ON public.pts_duty_rest_records(status,start_at,end_at);

-- Backend-only tables: no direct browser access. FastAPI authorizes every request
-- and accesses these tables using the Supabase service key held in server env.
DO $$ DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY[
    'pts_trainees','pts_trainee_attendance','pts_leave_records',
    'pts_osd_records','pts_duty_rest_records'
  ] LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY',t);
    EXECUTE format('REVOKE ALL ON TABLE public.%I FROM PUBLIC, anon, authenticated',t);
    EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.%I TO service_role',t);
  END LOOP;
END $$;

GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO service_role;

COMMENT ON TABLE public.pts_trainees IS
  'Police Training College Lahore Manawan trainee roster. Separate from any other academy database.';
COMMENT ON TABLE public.pts_trainee_attendance IS
  'Manawan trainee attendance by date and Morning/Evening shift.';
